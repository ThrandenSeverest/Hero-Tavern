'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const S=require('../manager/StoryState.cjs');
const {parseCommands,trackerInstructions}=require('../manager/TrackerDelta.cjs');
const {createStoryAPI}=require('../manager/StoryAPI.cjs');
const definition=S.validateDefinition({id:'supplies',owner:'character:mira',label:'Supplies',type:'record',initialValue:{summary:'Unreported',items:[]},dynamicFields:true,updateMode:'automatic',instructions:'Use established supplies in dialogue.'});
const m=(text,id='turn-new')=>({mes:text,is_user:false,extra:{heroMessageId:id}});
const key=S.keyOf(definition);
test('local LLM can cite sourceIndex without UUID, use typed JSON, and append flexible record facts',()=>{
 const messages=[m('Mira receives two lanterns from the merchant.')],state=S.initialState([definition]);
 const answer='Here are your updates:\n```json\n'+JSON.stringify({changes:[{key,sourceIndex:0,value:{summary:'Two lanterns acquired',items:['two lanterns'],lastAcquired:'merchant'},evidence:'receives two lanterns from the merchant'}]})+'\n```';
 const parsed=parseCommands(answer,[definition],messages,state);
 assert.equal(parsed.issues.length,0,JSON.stringify(parsed.issues));
 assert.equal(parsed.changes[0].sourceMessageId,'turn-new');
 assert.equal(parsed.changes[0].value.lastAcquired,'merchant');
 const session={definitions:[definition],events:[]};
 const accepted=S.propose(session,messages,parsed.changes);
 session.events.push(...accepted);
 assert.equal(S.activeContext(session,messages).state[key].items[0],'two lanterns');
 assert.match(S.activeContext(session,messages).text,/two lanterns/);
 assert.match(trackerInstructions([definition],state,messages),/sourceIndex/);
});
test('invalid evidence cannot change the record, even with valid structure',()=>{
 const input={changes:[{key,sourceIndex:0,evidence:'Mira throws her lanterns away',value:{summary:'Empty',items:[]}}]};
 const result=parseCommands(JSON.stringify(input),[definition],[m('Mira receives two lanterns from the merchant.')],S.initialState([definition]));
 assert.equal(result.changes.length,0);assert.ok(result.issues.length>0);
});
test('partial failure retries with backoff; repaired local response can update and influence next reply',async()=>{
 const messages=[m('The merchant handed over a new lantern.')],session={id:'s',definitions:[definition],events:[],analyzedSources:[],failures:[]};
 const view=()=>({session,messages,context:S.activeContext(session,messages)});
 let calls=0,applies=0;
 const store={view,get:()=>session,saveSession:()=>{},eventPatch:(_id,changes)=>{applies++;session.events.push(...S.propose(session,messages,changes));return view()}};
 const replies=['not JSON',JSON.stringify({changes:[{key,sourceIndex:0,evidence:'handed over a new lantern',value:{summary:'Lantern acquired',items:['lantern']}}]})];
 const pipeline={generate:async()=>({choices:[{text:replies[Math.min(calls++,1)]}]})};
 const api=createStoryAPI(store,pipeline,{ready:()=>true});
 const first=await api.action('/story/analyze',{id:'s'});
 assert.equal(first.session.lastAnalysis.partial,false,'Model repair attempt should be accepted when second model response is valid');
 assert.equal(applies,1);
 assert.equal(session.analyzedSources.length,1);
 assert.match(view().context.text,/Lantern acquired/);
 const again=await api.action('/story/analyze',{id:'s'});
 assert.equal(again.session.events.length,1,'Same completed turn must not double-apply');
});
test('background extension schedules retries, and user-facing helper can install an AI bundle',()=>{
 const extension=fs.readFileSync(path.join(__dirname,'../extension/story.js'),'utf8');
 const panel=fs.readFileSync(path.join(__dirname,'../manager/StoryPanel.js'),'utf8');
 assert.match(extension,/analysis\.backlog>0/);
 assert.match(extension,/analysis\.retryAt/);
 assert.match(panel,/Add all /);
 assert.match(panel,/recentDialogue/);
 assert.match(panel,/Flexible record fields/);
});
